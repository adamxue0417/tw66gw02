HAL_StatusTypeDef USART2_SendData_DMA(uint8_t *data, uint16_t num)
{
  HAL_StatusTypeDef ret;

  if ((data == NULL) || (num == 0u))
  {
    return HAL_ERROR;
  }

  /* Recover from stale busy flag if HAL state is already ready. */
  if ((usart2_tx_busy != 0u) && (huart2.gState == HAL_UART_STATE_READY))
  {
    usart2_tx_busy = 0u;
  }

  if (usart2_tx_busy != 0u)
  {
    return HAL_BUSY;
  }

  usart2_tx_busy = 1u;
  ret = HAL_UART_Transmit_DMA(&huart2, data, num);
  if (ret != HAL_OK)
  {
    usart2_tx_busy = 0u;
  }
  return ret;
}

